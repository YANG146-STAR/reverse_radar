// ====== 硬件I2C底层（I2C1, PB6=SCL, PB7=SDA, CubeMX 已初始化） ======
// SSD1306 地址：8 位写地址 = 0x78，对应 7 位地址 0x3C
// HAL_I2C_Master_Transmit 要求 DevAddress 参数传入 8 位格式，因此直接用 0x78
#define OLED_I2C_ADDR  0x78
#define OLED_I2C_TO    100  // HAL I2C 单次超时 ms（不要改大！卡住就是 HAL_I2C 没超时）

extern void MX_I2C1_Init(void);

static void I2C1_ForceReady(void) {
    hi2c1.State = HAL_I2C_STATE_READY;
    hi2c1.Mode  = HAL_I2C_MODE_NONE;
}


static void I2C1_Recover(void) {
    I2C1_ForceReady();
    static uint8_t s_fail_cnt = 0;
    s_fail_cnt++;
    if (s_fail_cnt >= 2) {
        s_fail_cnt = 0;
        __HAL_RCC_I2C1_CLK_DISABLE();
        for (volatile uint32_t i = 0; i < 24; i++) __NOP();
        MX_I2C1_Init();
        NVIC_DisableIRQ(I2C1_EV_IRQn);
        NVIC_DisableIRQ(I2C1_ER_IRQn);
    }
}

static HAL_StatusTypeDef OLED_I2C_Send(uint8_t *buf, uint16_t len) {
    I2C1_ForceReady();
    HAL_StatusTypeDef st = HAL_I2C_Master_Transmit(&hi2c1, OLED_I2C_ADDR, buf, len, OLED_I2C_TO);
    if (st != HAL_OK) I2C1_Recover();
    return st;
}

// ====== SSD1306 命令 / 数据写入（硬件 I2C HAL）======
// SSD1306 I2C 协议：地址后第 1 字节 = 控制字节 (Co=0, D/C# = 0 表示命令, D/C# = 1 表示数据)

static void OLED_WriteCmd(uint8_t cmd)
{
    uint8_t buf[2] = {0x00, cmd};  // 控制字节 0x00 = 后续字节均为命令
    OLED_I2C_Send(buf, 2);
}

static void OLED_SetPos(uint8_t x, uint8_t page)
{
    OLED_WriteCmd(0xB0 + page);                 // 页地址 0-7
    OLED_WriteCmd(((x & 0xF0) >> 4) | 0x10);    // 列地址高4位
    OLED_WriteCmd(x & 0x0F);                    // 列地址低4位
}

