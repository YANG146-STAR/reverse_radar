// 扩展字符索引（在ASCII表之外），返回负值表示扩展槽
#define FONT_EXT_DEGREE  95   // ° 索引 = 95

static const uint8_t FontExt[1][7] = {
    /*'°'*/ {0x06,0x09,0x09,0x06,0x00,0x00,0x00},  // 度数符号
};

static const uint8_t* Font_Get(char c, int *is_ext)
{
    *is_ext = 0;
    if ((unsigned char)c == 0xB0) { *is_ext = 1; return FontExt[0]; }
    if (c >= 0x20 && c <= 0x7E) { return Font5x7[c - 0x20]; }
    return Font5x7[0];  // 默认空格
}

// ====== 对外接口 ======
void OLED_Init(void)
{
    HAL_Delay(100);  // 上电等待模块稳定

    OLED_WriteCmd(0xAE);  // 关显示
    OLED_WriteCmd(0xD5);  // 设置时钟分频
    OLED_WriteCmd(0x80);
    OLED_WriteCmd(0xA8);  // 设置多路复用
    OLED_WriteCmd(0x3F);  // 1/64占空比（128x64屏）
    OLED_WriteCmd(0xD3);  // 设置显示偏移
    OLED_WriteCmd(0x00);
    OLED_WriteCmd(0x40);  // 设置起始行
    OLED_WriteCmd(0x8D);  // 电荷泵设置
    OLED_WriteCmd(0x14);  // 开启电荷泵
    OLED_WriteCmd(0x20);  // 设置内存寻址模式
    OLED_WriteCmd(0x02);  // 页寻址模式
    OLED_WriteCmd(0xA1);  // 段重映射
    OLED_WriteCmd(0xC8);  // COM扫描方向
    OLED_WriteCmd(0xDA);  // 设置COM引脚硬件配置
    OLED_WriteCmd(0x12);
    OLED_WriteCmd(0x81);  // 设置对比度
    OLED_WriteCmd(0xCF);
    OLED_WriteCmd(0xD9);  // 设置预充电周期
    OLED_WriteCmd(0xF1);
    OLED_WriteCmd(0xDB);  // 设置VCOMH
    OLED_WriteCmd(0x40);
    OLED_WriteCmd(0xA4);  // 设置整体显示开启
    OLED_WriteCmd(0xA6);  // 设置正常显示（反相显示改0xA7）
    OLED_WriteCmd(0xAF);  // 开显示
}

void OLED_SetBrightness(uint8_t val)
{
    OLED_WriteCmd(0x81);  // 对比度设置命令
    OLED_WriteCmd(val);   // 0x00 ~ 0xFF
}

// ====== 显存缓冲（所有绘制先写缓冲，Refresh时统一推到屏幕） ======
static uint8_t OLED_Buffer[1024];  // 8页 × 128列
static uint8_t OLED_DirtyPages;    // 脏页标记 bit0-7 = 页0-7（只刷新变化页，省 I2C 时间）

void OLED_Clear(void)
{
    memset(OLED_Buffer, 0, sizeof(OLED_Buffer));
    OLED_DirtyPages = 0xFF;   // 全页置脏
    OLED_Refresh();
}

// x: 0-127 像素列, y: 0-7 页（字符高8像素）
void OLED_ShowString(uint8_t x, uint8_t y, const char *str)
{
    while (*str) {
        int is_ext;
        const uint8_t *glyph = Font_Get(*str++, &is_ext);
        for (uint8_t col = 0; col < 5; col++) {
            uint8_t colData = 0;
            for (uint8_t row = 0; row < 7; row++) {
                if (glyph[row] & (1 << (4 - col))) {  // 列反转（硬件水平镜像）
                    colData |= (1 << row);
                }
            }
            if (y < 8 && (uint16_t)x + col < 128) {
                OLED_Buffer[y * 128 + x + col] = colData;
                OLED_DirtyPages |= (1 << y);   // 标记该页为脏
            }
        }
        x += 6;
        if (x > 122) break;
    }
}

// 把缓冲推到屏幕：每页做一次批量 I2C 发送（控制字节 0x40 + 128 字节数据）
// 硬件 I2C 400KHz 下一次 Refresh 约 20ms，比逐字节 Send 快 100 倍
void OLED_Refresh(void)
{
    static uint8_t tx_buf[1 + 128];  // 1 字节控制头 + 128 字节列数据
    if (!OLED_DirtyPages) return;    // 无变化页直接跳过（省 ~20ms/帧）
    tx_buf[0] = 0x40;                // SSD1306 控制字节：D/C#=1 (显示数据)
    for (uint8_t page = 0; page < 8; page++) {
        if (!(OLED_DirtyPages & (1 << page))) continue;   // 只刷变化的页
        OLED_SetPos(0, page);
        memcpy(&tx_buf[1], &OLED_Buffer[page * 128], 128);
        OLED_I2C_Send(tx_buf, sizeof(tx_buf));   // 每次都走 ForceReady+失败恢复
    }
    OLED_DirtyPages = 0;             // 清脏
}
